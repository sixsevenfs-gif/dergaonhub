// Writes supabase/seed.sql: store settings, categories and the starter products from src/lib/seed.js.
// Run:  node scripts/make-seed-sql.mjs   then paste supabase/seed.sql into Supabase → SQL Editor.
import { writeFileSync } from 'node:fs'
import { makeSeed } from '../src/lib/seed.js'

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const arr = (list) => `array[${list.map(q).join(', ')}]::text[]`

const seed = makeSeed()
const s = seed.store
const lines = [
  '-- Starter data for Dergaon Hub. Generated by scripts/make-seed-sql.mjs — run after schema.sql.',
  '-- Phone numbers and the home location are placeholders: change them in Admin → Settings.',
  '',
  'insert into public.store_settings (id, name, phone, whatsapp, open_time, close_time, cutoff_time, slot_start, slot_end,',
  '  min_order, delivery_area, paused, lat, lng, per_km_fee, min_delivery_fee, max_delivery_km)',
  `values (1, ${q(s.name)}, ${q(s.phone)}, ${q(s.whatsapp)}, ${q(s.open_time)}, ${q(s.close_time)}, ${q(s.cutoff_time)}, ${q(s.slot_start)}, ${q(s.slot_end)},`,
  `  ${s.min_order}, ${arr(s.delivery_area)}, false, ${s.location.lat}, ${s.location.lng}, ${s.per_km_fee}, ${s.min_delivery_fee}, ${s.max_delivery_km})`,
  'on conflict (id) do nothing;',
  '',
  'insert into public.categories (id, name, short, sort) values',
  seed.categories.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.short)}, ${i})`).join(',\n'),
  'on conflict (id) do nothing;',
  '',
  'insert into public.products (name, size, category_id, keywords, price, photo_url, featured, available) values',
  seed.products
    .map((p) => `  (${q(p.name)}, ${q(p.size)}, ${q(p.category_id)}, ${q(p.keywords)}, ${p.price}, ${q(p.photo_url)}, ${p.featured}, ${p.available})`)
    .join(',\n') + ';',
  '',
]
writeFileSync('supabase/seed.sql', lines.join('\n'))
console.log(`supabase/seed.sql: ${seed.categories.length} categories, ${seed.products.length} products`)
